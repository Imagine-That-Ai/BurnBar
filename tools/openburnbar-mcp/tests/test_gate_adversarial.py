def test_the_corpus_detects_enough_shapes_for_this_suite_to_have_teeth():
    assert len(DETECTED) >= 12, {"detected": sorted(DETECTED), "missed": sorted(set(SHAPES) - set(DETECTED))}


@pytest.mark.parametrize("context", CONTEXTS)
def test_redact_policy_leaves_no_surface_with_the_raw_token(context: str, gate_store: tuple[Path, str]) -> None:
    db_path, project_path = gate_store
    engine = _open(db_path, secret_policy="redact")
    results: list[dict[str, Any]] = []
    memory_ids: list[str] = []
    try:
        for label, token in DETECTED.items():
            result = engine.remember(project_path=project_path, kind="fact", **_write_kwargs(context, label, token))
            results.append(result)
            if result.get("memoryID"):
                memory_ids.append(str(result["memoryID"]))
        surfaces = _readable_surfaces(engine, project_path, memory_ids, results)
    finally:
        engine.close()

    leaks = [
        f"{label}: {surface}"
        for label, token in DETECTED.items()
        for surface, values in surfaces.items()
        if any(token in value for value in values)
    ] + _tokens_on_disk(db_path)
    assert not leaks, leaks


@pytest.mark.parametrize("context", CONTEXTS)
def test_reject_policy_refuses_every_detected_shape(context: str, gate_store: tuple[Path, str]) -> None:
    db_path, project_path = gate_store
    engine = _open(db_path, secret_policy="reject")
    try:
        accepted = []
        for label, token in DETECTED.items():
            result = engine.remember(project_path=project_path, kind="fact", **_write_kwargs(context, label, token))
            if (result.get("status"), result.get("event"), result.get("code")) != (
                "rejected",
                "REJECT",
                "SECRET_DETECTED",
            ):
                accepted.append((label, result.get("status"), result.get("event"), result.get("code")))
        assert not accepted, accepted
        assert engine.list(project_path=project_path, page_size=100)["results"] == []
    finally:
        engine.close()

    assert not _tokens_on_disk(db_path)


def _found_case_insensitively(db_path: Path, token: str) -> bool:
    """Is `token` in the store bytes under any casing?

    Normalization lowercases a tag, so a case-sensitive search would miss exactly
    the leak this checks for.
    """
    return token.encode("utf-8").lower() in _store_bytes(db_path).lower()


@pytest.mark.parametrize("context", AUX_CONTEXTS)
def test_an_aws_key_in_an_aux_field_is_gated_before_normalization(context: str, gate_store: tuple[Path, str]) -> None:
    """The auxiliary gate must see the caller's raw string, not the normalized one."""
    db_path, project_path = gate_store
    token = SHAPES[CASE_SENSITIVE_SHAPE]
    planted = _write_kwargs(context, "aws", token)

    reject_db = db_path.with_name("reject.sqlite")
    engine = _open(reject_db, secret_policy="reject")
    try:
        refused = engine.remember(project_path=project_path, kind="fact", **planted)
        assert (refused.get("status"), refused.get("event"), refused.get("code")) == (
            "rejected",
            "REJECT",
            "SECRET_DETECTED",
        ), refused
        assert engine.list(project_path=project_path, page_size=100)["results"] == []
    finally:
        engine.close()
    assert not _found_case_insensitively(reject_db, token)

    engine = _open(db_path, secret_policy="redact")
    try:
        written = engine.remember(project_path=project_path, kind="fact", **planted)
        assert written["status"] == "ok", written
        surfaces = _readable_surfaces(engine, project_path, [str(written["memoryID"])], [written])
    finally:
        engine.close()

    leaks = [
        f"{surface}: {value}"
        for surface, values in surfaces.items()
        for value in values
        if token.lower() in value.lower()
    ]
    assert not leaks, leaks
    assert not _found_case_insensitively(db_path, token)



"""Adversarial secret-gate suite.

Every secret shape the shared corpus flags standalone is planted in eight
places a caller controls -- prose, a key/value line, a fenced code block, a
tag, an entity, a metadata value and a source ref -- and every policy is held
to its promise:

* ``redact``: the verbatim token survives in no surface the engine can return,
  and not in the raw bytes of the store either;
* ``reject``: the write is refused and no row lands;
* ``retain``: the vault decrypts to the verbatim token while the plaintext
  body and the file bytes still do not contain it.

Seeded, offline, and dependency-free: the tokens come from
``eval_memory.SECRET_SHAPES``, generated by ``random.Random(20260902)`` so
nothing of token shape is ever committed; the embedding provider is off, so no
network or Ollama call happens.

Auxiliary fields are gated on their raw, pre-normalization form, so a tag is
held to the same promise as the body even though the stored tag is lowercased.
``test_an_aws_key_in_an_aux_field_is_gated_before_normalization`` pins that
directly with the shape that exposed the bug.
"""

from __future__ import annotations

import base64
import json
import sys
from pathlib import Path
from typing import Any

import pytest

MCP_DIR = Path(__file__).resolve().parents[1]
if str(MCP_DIR) not in sys.path:
    sys.path.insert(0, str(MCP_DIR))

import eval_memory  # noqa: E402
import memory_engine as me  # noqa: E402

SHAPES: dict[str, str] = eval_memory.SECRET_SHAPES
FIXED_KEY = base64.b64encode(bytes(range(32))).decode("ascii")
RECALL_QUERY = "burnbar release runner credential rotated"

BODY_CONTEXTS = ("prose_middle", "prose_end", "key_line", "code_fence")
AUX_CONTEXTS = ("tag", "entity", "metadata", "source_ref")
CONTEXTS = BODY_CONTEXTS + AUX_CONTEXTS


def detected_shapes() -> dict[str, str]:
    """The shapes the corpus flags standalone -- the only ones this suite can hold
    the gate to. A shape the scanner cannot see is a corpus gap, not a gate bug;
    `eval_memory.run_gate_matrix` is where that coverage is reported."""
    return {name: token for name, token in SHAPES.items() if me.scan_text(token).secret_labels}


DETECTED = detected_shapes()

# Lowercased, an AWS access key id matches no corpus pattern and sits under the
# entropy floor, so it is the shape that catches a gate running after
# `normalize_tags` instead of before it.
CASE_SENSITIVE_SHAPE = "aws_access_key_id"


def _prose(label: str) -> str:
    return f"The {label} credential for the burnbar release runner is rotated every ninety days."


def _write_kwargs(context: str, label: str, token: str) -> dict[str, Any]:
    """The `remember` arguments that plant `token` in `context`."""
    prose = _prose(label)
    bodies = {
        "prose_middle": f"{prose} It is currently {token} and only the runner may read it.",
        "prose_end": f"{prose} The current value is {token}",
        "key_line": f"{prose}\ncredential: {token}",
        "code_fence": f"{prose}\n\n```sh\nexport RUNNER_CREDENTIAL={token}\n```",
    }
    if context in bodies:
        return {"text": bodies[context]}
    aux: dict[str, dict[str, Any]] = {
        "tag": {"tags": [token]},
        "entity": {"entities": [token]},
        "metadata": {"metadata": {"credential": token}},
        "source_ref": {"source_ref": token},
    }
    return {"text": prose, **aux[context]}


def _strings(value: Any, found: list[str] | None = None) -> list[str]:
    """Every string anywhere in a returned payload, dict keys included."""
    out = [] if found is None else found
    if isinstance(value, str):
        out.append(value)
    elif isinstance(value, dict):
        for key, item in value.items():
            _strings(key, out)
            _strings(item, out)
    elif isinstance(value, (list, tuple)):
        for item in value:
            _strings(item, out)
    return out


def _open(db_path: Path, *, secret_policy: str, retain_allowed: bool = False) -> me.MemoryEngine:
    return me.MemoryEngine.open(
        db_path,
        provider=me.NullEmbeddingProvider("adversarial gate suite"),
        config=me.EngineConfig(secret_policy=secret_policy, pii_policy="keep", retain_allowed=retain_allowed),
    )


def _store_bytes(db_path: Path) -> bytes:
    """The store as it sits on disk: the main file plus any un-checkpointed WAL."""
    raw = db_path.read_bytes()
    wal = db_path.with_name(db_path.name + "-wal")
    if wal.exists():
        raw += wal.read_bytes()
    return raw


def _tokens_on_disk(db_path: Path) -> list[str]:
    blob = _store_bytes(db_path)
    return [f"{label}: store bytes" for label, token in DETECTED.items() if token.encode("utf-8") in blob]


def _readable_surfaces(
    engine: me.MemoryEngine, project_path: str, memory_ids: list[str], results: list[dict[str, Any]]
) -> dict[str, list[str]]:
    """Every plaintext an agent can pull back out of the engine."""
    return {
        "write result": _strings(results),
        "get": _strings([engine.get(memory_id) for memory_id in memory_ids]),
        "history": _strings([engine.history(memory_id) for memory_id in memory_ids]),
        "list": _strings(engine.list(project_path=project_path, page_size=100)),
        "recall": _strings(
            engine.recall(
                RECALL_QUERY,
                project_path=project_path,
                limit=100,
                reinforce=False,
                include_quarantined=True,
                include_superseded=True,
                include_expired=True,
                include_secrets=True,
            )
        ),
        "pack": _strings(engine.recall_pack(RECALL_QUERY, project_path=project_path, token_budget=100_000, limit=100)),
        "export": _strings(engine.export(project_path=project_path, include_superseded=True)),
        "audit trail": _strings(engine.audit_trail(project_path=project_path, limit=500)),
    }



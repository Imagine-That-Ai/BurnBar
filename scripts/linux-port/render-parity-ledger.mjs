#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { repoRoot } from './lib/linux-release-common.mjs';

function cell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}

export function renderParityLedger(ledger, requirements) {
  const byId = new Map(requirements.requirements.map((requirement) => [requirement.id, requirement]));
  const ready = ledger.rows.filter((row) => row.status === 'ready').length;
  const blocked = ledger.rows.length - ready;
  const claim = ledger.semantics?.productParityClaim === true;
  const lines = [
    '# Linux/macOS product parity ledger',
    '',
    '> Generated from `parity-ledger.json` and `product-parity-requirements.json`.',
    '> Run `node scripts/linux-port/render-parity-ledger.mjs`; do not edit this file manually.',
    '',
    '## Status',
    '',
    `- Product parity claim: **${claim ? 'true' : 'false'}**`,
    `- Product requirements: **${ledger.rows.length}** (${ready} ready, ${blocked} blocked)`,
    `- Minimum support environments: **${ledger.environmentCoverage.length}**`,
    `- Gold standard: ${ledger.semantics.goldStandard}`,
    `- Audit: [independent parity audit](${path.basename(ledger.semantics.audit)})`,
    `- Historical evidence: [parity-ledger-history.json](${path.basename(ledger.historyLedger)})`,
    '',
    'A green structural check means the inventory is complete and internally valid. It does not',
    'mean Linux is promotable. Promotion requires every product and environment row to be ready',
    'with a generated current-HEAD attestation and verified artifact hashes.',
    '',
    '## Product Requirements',
    '',
    '| ID | Area | Priority | Tier | Status | Owner | Promotion criterion |',
    '|---|---|---:|:---:|:---:|---|---|'
  ];

  for (const row of ledger.rows) {
    const requirement = byId.get(row.requirementId) ?? {};
    lines.push(
      `| ${cell(row.id)} | ${cell(requirement.area)} | ${cell(requirement.priority)} | ${cell(row.tier)} | ${cell(row.status)} | ${cell(row.owner)} | ${cell(row.promotionCriterion)} |`
    );
  }

  lines.push(
    '',
    '## Minimum Support Matrix',
    '',
    '| Environment | OS | Desktop | Session | Architecture | Status |',
    '|---|---|---|---|---|:---:|'
  );
  const environmentById = new Map(
    requirements.minimumSupportMatrix.map((environment) => [environment.id, environment])
  );
  for (const coverage of ledger.environmentCoverage) {
    const environment = environmentById.get(coverage.id) ?? {};
    lines.push(
      `| ${cell(coverage.id)} | ${cell(environment.os)} | ${cell(environment.desktop)} | ${cell(environment.session)} | ${cell(environment.architecture)} | ${cell(coverage.status)} |`
    );
  }

  lines.push(
    '',
    '## Validation',
    '',
    '```bash',
    '# Inventory/schema/path integrity. Blocked work remains visible but does not fail this mode.',
    'node scripts/linux-port/validate-parity-ledger.mjs --allow-blocked',
    '',
    '# Promotion gate. This must remain nonzero until every requirement and environment is proven.',
    'node scripts/linux-port/validate-parity-ledger.mjs',
    '',
    '# Generated documentation drift check.',
    'node scripts/linux-port/render-parity-ledger.mjs --check',
    '```',
    ''
  );
  return lines.join('\n');
}

function main() {
  const ledgerPath = path.join(repoRoot, 'docs/linux-port/parity-ledger.json');
  const requirementsPath = path.join(repoRoot, 'docs/linux-port/product-parity-requirements.json');
  const outputPath = path.join(repoRoot, 'docs/linux-port/parity-ledger.md');
  const rendered = renderParityLedger(
    JSON.parse(fs.readFileSync(ledgerPath, 'utf8')),
    JSON.parse(fs.readFileSync(requirementsPath, 'utf8'))
  );
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (current !== rendered) {
      console.error('docs/linux-port/parity-ledger.md is stale; run render-parity-ledger.mjs.');
      process.exit(1);
    }
    return;
  }
  fs.writeFileSync(outputPath, rendered, 'utf8');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

#!/usr/bin/env node
/**
 * Static confidentiality gate for the scheduled Factory security review.
 *
 * The workflow may generate raw security findings, but those findings must not
 * be printed to CI logs, passed through long-lived shell argv, uploaded as
 * artifacts, routed to Slack as a substitute for a private advisory, or allowed
 * to poison later secret-bearing steps through GitHub Actions state files.
 */

import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT =
  process.env.FACTORY_SECURITY_REVIEW_BOUNDARY_ROOT ??
  join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const WORKFLOW = join(ROOT, ".github/workflows/factory-security-review.yml");

const failures = [];
const fail = (message) => failures.push(message);

function stripYamlLineComment(line) {
  let singleQuoted = false;
  let doubleQuoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    const previous = index > 0 ? line[index - 1] : "";
    if (char === "'" && !doubleQuoted) {
      singleQuoted = !singleQuoted;
      continue;
    }
    if (char === '"' && !singleQuoted && previous !== "\\") {
      doubleQuoted = !doubleQuoted;
      continue;
    }
    if (
      char === "#" &&
      !singleQuoted &&
      !doubleQuoted &&
      (index === 0 || /\s/u.test(previous))
    ) {
      return line.slice(0, index).trimEnd();
    }
  }
  return line;
}

const stripComments = (source) =>
  source
    .split("\n")
    .map((line) => stripYamlLineComment(line))
    .join("\n");

if (!existsSync(WORKFLOW)) {
  console.error(`MISCONFIGURED: workflow not found: ${WORKFLOW}`);
  process.exit(2);
}

const rawSource = readFileSync(WORKFLOW, "utf8");
const source = stripComments(rawSource);

if (/\bset\s+-x\b/u.test(source)) {
  fail("workflow must not enable shell xtrace around security reports");
}

if (!/review_output="\$\{RUNNER_TEMP\}\/factory-security-review-output\.log"/u.test(source)) {
  fail("Droid mission output must be captured to a runner-temp file");
}

if (!/if ! \{\s+sudo -H -u "\$\{mission_user\}" env -i[\s\S]*"\$\{droid_bin\}" exec --mission --auto high/u.test(source)) {
  fail("Droid mission must run behind an explicit fail-closed wrapper");
}

const missionBlock =
  source.match(
    /if ! \{\s+sudo -H -u "\$\{mission_user\}" env -i[\s\S]*?"\$\{droid_bin\}" exec --mission --auto high[\s\S]*?\/security-review[\s\S]*?2>&1/u,
  )?.[0] ?? "";
if (!missionBlock) {
  fail("Droid mission must execute through a sanitized child environment");
} else {
  for (const marker of [
    'FACTORY_API_KEY="${FACTORY_API_KEY}"',
    'FACTORY_SECURITY_MODEL="${FACTORY_SECURITY_MODEL}"',
    'FACTORY_REASONING_EFFORT="${FACTORY_REASONING_EFFORT}"',
    'HOME="${mission_home}"',
    'RUNNER_TEMP="${mission_tmp}"',
    'TMPDIR="${mission_tmp}"',
  ]) {
    if (!missionBlock.includes(marker)) {
      fail(`Droid mission sanitized environment is missing ${marker}`);
    }
  }
  for (const forbidden of [
    "GITHUB_ENV",
    "GITHUB_PATH",
    "GITHUB_OUTPUT",
    "GITHUB_STEP_SUMMARY",
    "GITHUB_TOKEN",
    "GH_TOKEN",
    "SLACK_SECURITY_WEBHOOK",
    "BASH_ENV",
    "ENV=",
    'RUNNER_TEMP="${RUNNER_TEMP}"',
  ]) {
    if (missionBlock.includes(forbidden)) {
      fail(`Droid mission sanitized environment must not pass ${forbidden}`);
    }
  }
}

if (!/>"\$\{review_output\}" 2>&1/u.test(source)) {
  fail("Droid mission stdout/stderr must not stream to CI logs");
}

if (/exec --mission[\s\S]*?\/security-review[\s\S]*?(?<!>)\n/u.test(source)) {
  if (!missionBlock.includes('>"${review_output}" 2>&1')) {
    fail("Droid mission command appears without the required output redirection");
  }
}

const artifactUploadBlocks = Array.from(
  source.matchAll(/uses:\s*actions\/upload-artifact@[^\n]*(?:\n(?!\s*-\s+name:)[^\n]*)*/gu),
  (match) => match[0],
);
for (const uploadBlock of artifactUploadBlocks) {
  if (/security-audits|report_tmp|description_tmp|payload_tmp|factory-security-review-output/u.test(uploadBlock)) {
    fail("raw security review outputs must not be uploaded as artifacts");
  }
}

const encryptedEvidenceUpload = artifactUploadBlocks.find((block) =>
  block.includes("factory-security-review-encrypted-evidence"),
);
if (!encryptedEvidenceUpload) {
  fail("critical review evidence must be retained through the encrypted evidence artifact path");
} else {
  for (const marker of [
    "path: ${{ runner.temp }}/factory-security-review-encrypted-evidence.tgz.gpg",
    "if-no-files-found: ignore",
    "retention-days: 30",
  ]) {
    if (!encryptedEvidenceUpload.includes(marker)) {
      fail(`encrypted evidence upload is missing ${marker}`);
    }
  }
}

const sourceWithoutDescriptionBlock = source.replace(
  /\{\s*\n\s*printf 'Auto-generated by the Factory Security Review workflow[\s\S]*?\n\s*head\s+-c\s+"\$\{max_chars\}"\s+"\$\{report_tmp\}"\s*\n\s*\}\s*>\s*"\$\{description_tmp\}"/u,
  "",
);
if (/^\s*(?:cat|tail|head)\b[^\n]*"\$\{report_tmp\}"/mu.test(sourceWithoutDescriptionBlock)) {
  fail("combined security report must not be printed to CI logs");
}

if (/\becho\s+.*\$\{?(?:body|report_tmp|description_tmp)\}?/u.test(source)) {
  fail("security report buffers must not be echoed to CI logs");
}

if (/-f\s+description=|-F\s+description=|body="\$\(head -c/u.test(source)) {
  fail("private advisory body must not be passed through shell argv");
}

if (!/--rawfile description "\$\{description_tmp\}"/u.test(source)) {
  fail("private advisory body must be loaded by jq from a temp file");
}

if (!/--input "\$\{payload_tmp\}"/u.test(source)) {
  fail("GitHub advisory API call must read the JSON payload from a file");
}

if (!/mission_user="factory-mission"/u.test(source) || !/sudo useradd --create-home --shell \/usr\/sbin\/nologin "\$\{mission_user\}"/u.test(source)) {
  fail("Droid mission must run as a dedicated unprivileged user");
}

if (!/mission_home="\$\{mission_root\}\/home"/u.test(source) || !/mission_tmp="\$\{mission_root\}\/tmp"/u.test(source)) {
  fail("Droid mission must receive isolated home and temp directories");
}

if (!/npm_global_bin="\$\(npm prefix --global\)\/bin"/u.test(source) || !/droid_bin="\$\{npm_global_bin\}\/droid"/u.test(source)) {
  fail("Droid mission must resolve the pinned npm-installed CLI before narrowing PATH");
}

if (!/export PATH="\/usr\/bin:\/bin:\/usr\/sbin:\/sbin"/u.test(source)) {
  fail("secret-bearing routing step must reset PATH to trusted system directories");
}

if (!/unset BASH_ENV ENV CDPATH/u.test(source)) {
  fail("secret-bearing routing step must clear shell environment hooks");
}

if (!/gh_bin="\/usr\/bin\/gh"/u.test(source)) {
  fail("secret-bearing routing step must use the fixed system gh binary");
}

if (!/jq_bin="\/usr\/bin\/jq"/u.test(source)) {
  fail("secret-bearing routing step must use the fixed system jq binary");
}

if (!/curl_bin="\/usr\/bin\/curl"/u.test(source)) {
  fail("secret-bearing routing step must use the fixed system curl binary");
}

if (!/gpg_bin="\/usr\/bin\/gpg"/u.test(source)) {
  fail("secret-bearing routing step must use the fixed system gpg binary");
}

if (!/tar_bin="\/usr\/bin\/tar"/u.test(source)) {
  fail("secret-bearing routing step must use the fixed system tar binary");
}

if (!/"\$\{gh_bin\}" api --silent --method POST/u.test(source)) {
  fail("GitHub advisory API call must suppress the response body");
}

if (!/"\$\{jq_bin\}" -n\s/u.test(source) || !/"\$\{jq_bin\}" -nc\s/u.test(source)) {
  fail("secret-bearing routing step must invoke jq through the trusted resolved path");
}

if (/^\s*jq\s+-n[ c]?/mu.test(source) || /\$\(\s*jq\s+-n[ c]?/mu.test(source)) {
  fail("secret-bearing routing step must not resolve jq through PATH");
}

if (!/"\$\{curl_bin\}" -fsS -X POST/u.test(source)) {
  fail("secret-bearing routing step must invoke curl through the trusted resolved path");
}

if (/^\s*curl\s+-/mu.test(source)) {
  fail("secret-bearing routing step must not resolve curl through PATH");
}

if (!/"\$\{gpg_bin\}" --batch --yes --pinentry-mode loopback[\s\S]*--symmetric --cipher-algo AES256[\s\S]*--s2k-digest-algo SHA512[\s\S]*--passphrase-fd 3[\s\S]*3<<<"\$\{SECURITY_REVIEW_EVIDENCE_KEY\}"/u.test(
  source,
)) {
  fail("encrypted evidence retention must use trusted gpg with passphrase-fd, not shell argv");
}

if (/^\s*gpg\s+--/mu.test(source)) {
  fail("encrypted evidence retention must not resolve gpg through PATH");
}

if (!/"\$\{tar_bin\}" -czf - report\.txt metadata\.json/u.test(source)) {
  fail("encrypted evidence retention must package only the report and metadata");
}

if (/^\s*tar\s+-/mu.test(source)) {
  fail("encrypted evidence retention must not resolve tar through PATH");
}

if (!/GH_TOKEN:\s*\$\{\{\s*secrets\.SECURITY_ADVISORY_TOKEN\s*\}\}/u.test(source)) {
  fail("GitHub advisory API call must use an advisory-capable token secret");
}

if (!/SECURITY_REVIEW_EVIDENCE_KEY:\s*\$\{\{\s*secrets\.SECURITY_REVIEW_EVIDENCE_KEY\s*\}\}/u.test(source)) {
  fail("encrypted evidence retention must use the dedicated evidence key secret");
}

if (!/confidential: true/u.test(source)) {
  fail("advisory payload must mark reports confidential");
}

if (!/ecosystem:\s*\\?"other\\?"/u.test(source)) {
  fail("advisory payload must use GitHub's lowercase advisory ecosystem value");
}

if (/ecosystem:\s*\\?"OTHER\\?"/u.test(source)) {
  fail("advisory payload must not use uppercase advisory ecosystem values");
}

if (/review full report in CI logs|full report in CI logs/iu.test(source)) {
  fail("workflow must never direct humans to raw findings in CI logs");
}

if (
  source.includes(
    'advisory_created}" == "false" && "${slack_sent',
  )
) {
  fail("Slack notification must not substitute for private advisory routing");
}

if (!/Slack is\s+#?\s*only an alert|Slack is[\s\S]*never a substitute/u.test(rawSource)) {
  fail("workflow must document Slack as alert-only routing");
}

if (!/Critical findings detected but private advisory routing failed/u.test(source)) {
  fail("critical findings must fail closed when private advisory routing fails");
}

if (failures.length > 0) {
  console.error("Factory security review boundary verification failed:");
  for (const failure of failures) console.error(`  - ${failure}`);
  process.exit(1);
}

console.log("PASS: Factory security review keeps raw findings out of CI logs, shell argv, and unencrypted artifacts.");

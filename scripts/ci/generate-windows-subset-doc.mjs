#!/usr/bin/env node
// Wave 2.3: generate the Windows port's fenced-subset schema doc.
//
// Windows provisions an EXPERIMENTAL SUBSET of the canonical SQLite schema
// (fresh installs only need the shipped Windows subsystems; Mac-transferred
// databases bring the rest). This generator renders that fence as a readable
// doc from the same extractor scripts/check-migrator-parity.mjs trusts plus
// the annotated reasons in budgets/migrator-parity-baseline.json:
//
//   node scripts/ci/generate-windows-subset-doc.mjs [--check] [--output <path>]
//
// --check diffs against the committed doc instead of writing it (CI).
// Default output: windows/storage/OpenBurnBar.Storage/SCHEMA_SUBSET.md.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SURFACES,
  extractSwiftMigrations,
  replayMigrations,
  extractWindows,
  loadBaseline,
} from "../check-migrator-parity.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const DEFAULT_OUTPUT = join(
  "windows",
  "storage",
  "OpenBurnBar.Storage",
  "SCHEMA_SUBSET.md"
);

function parseArgs(argv) {
  const options = { check: false, output: DEFAULT_OUTPUT };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") options.check = true;
    else if (arg === "--output") {
      options.output = argv[i + 1] ?? "";
      i += 1;
      if (!options.output) throw new Error("--output needs a value");
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return options;
}

function firstSentence(reason) {
  const match = reason.match(/^(.*?\.)\s/);
  return match ? match[1] : reason;
}

function generate() {
  const canon = extractSwiftMigrations(
    repoRoot,
    SURFACES.swiftCanon,
    (dir) => readdirSync(dir)
  );
  const canonState = replayMigrations(canon.migrations);
  const windows = extractWindows(repoRoot, SURFACES.windows);
  const baseline = loadBaseline(repoRoot);
  const reasons = new Map(
    (baseline.divergences ?? []).map((d) => [d.key, d.reason])
  );

  const endpoint = canon.identifiers[canon.identifiers.length - 1];
  const canonTables = [...canonState.tables.keys()].sort();
  const canonVirtual = [...canonState.virtualTables.keys()].sort();
  const portedTables = [...windows.state.tables.keys()].sort();
  const portedVirtual = [...windows.state.virtualTables.keys()].sort();
  const ported = new Set([...portedTables, ...portedVirtual]);
  const unported = [...canonTables, ...canonVirtual]
    .filter((t) => !ported.has(t))
    .sort();

  const lines = [];
  lines.push("<!-- GENERATED BY `node scripts/ci/generate-windows-subset-doc.mjs`.");
  lines.push("     DO NOT EDIT: regenerate after any migrator, Windows schema, or");
  lines.push("     parity-baseline change; CI fails on any drift. -->");
  lines.push("# Windows Storage Schema Subset (experimental)");
  lines.push("");
  lines.push(
    `Canonical endpoint: \`${endpoint}\` (${canon.identifiers.length} migrations). ` +
      `Windows journal: ${windows.identifiers.length} identifiers ending at ` +
      `\`${windows.endpoint}\` (count ${windows.count}).`
  );
  lines.push("");
  lines.push(
    "Windows fresh-install provisioning mirrors only the shipped Windows " +
      "subsystems (token usage, conversations + standalone FTS, chat " +
      "threads/messages, budgets, switcher). Tables outside that subset are " +
      "NOT created by the provisioner; Windows reads them only from " +
      "Mac-transferred databases where the Mac migrator created them. The " +
      "full canonical schema is `docs/SCHEMA_SQLITE.sql` (generated from the " +
      "live migrator); per-object drift is enforced by " +
      "`scripts/check-migrator-parity.mjs` with annotated reasons in " +
      "`budgets/migrator-parity-baseline.json` — this doc renders that fence " +
      "readably, it does not define it."
  );
  lines.push("");
  lines.push(
    `## Ported tables (${portedTables.length + portedVirtual.length})`
  );
  lines.push("");
  lines.push("| Table | Columns (as provisioned) | Notes |");
  lines.push("|---|---|---|");
  for (const table of [...portedTables, ...portedVirtual]) {
    const cols =
      windows.state.tables.get(table) ??
      new Set(windows.state.virtualTables.get(table)?.columns ?? []);
    const virtual = windows.state.virtualTables.has(table)
      ? " (FTS virtual)"
      : "";
    const notes = [];
    for (const [key, reason] of reasons) {
      if (key.startsWith(`windows:table:${table}:`)) {
        notes.push(firstSentence(reason));
      }
    }
    for (const [key, reason] of reasons) {
      if (key === `windows:fts-config:${table}`) {
        notes.push(firstSentence(reason));
      }
    }
    lines.push(
      `| \`${table}\`${virtual} | ${[...cols].map((c) => `\`${c}\``).join(", ")} | ${notes.join(" ")} |`
    );
  }
  lines.push("");
  lines.push(`## Not ported (${unported.length})`);
  lines.push("");
  lines.push("| Table | Reason (from the parity baseline) |");
  lines.push("|---|---|");
  for (const table of unported) {
    const reason =
      reasons.get(`windows:missing-table:${table}`) ??
      "(no annotated reason — parity check failure)";
    lines.push(`| \`${table}\` | ${reason} |`);
  }
  lines.push("");
  return `${lines.join("\n")}`;
}

function main(argv) {
  const options = parseArgs(argv);
  const document = generate();
  const outputPath = join(repoRoot, options.output);
  if (options.check) {
    const committed = readFileSync(outputPath, "utf8");
    if (committed !== document) {
      console.error(
        `Windows subset doc drifted: ${options.output} does not match a fresh render.\n` +
          `Run \`node scripts/ci/generate-windows-subset-doc.mjs\` and commit the result.`
      );
      process.exit(1);
    }
    console.log(`Windows subset doc is fresh (${options.output}).`);
    return;
  }
  writeFileSync(outputPath, document);
  console.log(`Wrote ${outputPath}.`);
}

const isDirectRun =
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`Windows subset doc generation FAILED: ${error.message}`);
    process.exit(1);
  }
}

#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(repoRoot, 'contracts/provider-ingestion-catalog.json');
const swiftPath = path.join(
  repoRoot,
  'OpenBurnBarCore/Sources/OpenBurnBarParserSupport/AgentProviderIngestionCatalog.generated.swift'
);
const checkOnly = process.argv.includes('--check');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.providers)) {
  throw new Error('provider ingestion manifest must use schemaVersion 1 and contain providers');
}

const required = new Set([
  'providerId',
  'agentProviderCase',
  'displayLabel',
  'aliases',
  'paths',
  'filePattern',
  'ingestion',
  'coverageNote',
  'xdgBehavior',
  'symlinkBehavior',
  'quotaSignal'
]);
const providerIDs = new Set();
const providerCases = new Set();
for (const [index, provider] of manifest.providers.entries()) {
  for (const key of required) {
    if (!(key in provider)) throw new Error(`providers[${index}] is missing ${key}`);
  }
  if (providerIDs.has(provider.providerId)) throw new Error(`duplicate providerId ${provider.providerId}`);
  if (providerCases.has(provider.agentProviderCase)) {
    throw new Error(`duplicate agentProviderCase ${provider.agentProviderCase}`);
  }
  providerIDs.add(provider.providerId);
  providerCases.add(provider.agentProviderCase);
  if (!['local-parser', 'api-backed', 'unavailable'].includes(provider.ingestion)) {
    throw new Error(`providers[${index}] has unsupported ingestion ${provider.ingestion}`);
  }
  if (typeof provider.paths?.linux !== 'string' || typeof provider.paths?.macos !== 'string') {
    throw new Error(`providers[${index}] must declare Linux and macOS paths`);
  }
}

const swiftString = (value) => JSON.stringify(String(value));
const coverageCase = (value) => ({
  'local-parser': 'localParser',
  'api-backed': 'apiBacked',
  unavailable: 'unavailable'
})[value];

const entries = manifest.providers.map((provider) => `
        Entry(
            provider: .${provider.agentProviderCase},
            agentProviderCase: ${swiftString(provider.agentProviderCase)},
            providerID: ${swiftString(provider.providerId)},
            displayLabel: ${swiftString(provider.displayLabel)},
            aliases: [${provider.aliases.map(swiftString).join(', ')}],
            linuxLogicalPath: ${swiftString(provider.paths.linux)},
            macOSLogicalPath: ${swiftString(provider.paths.macos)},
            filePattern: ${swiftString(provider.filePattern)},
            ingestion: .${coverageCase(provider.ingestion)},
            coverageNote: ${swiftString(provider.coverageNote)},
            quotaSignal: ${provider.quotaSignal ? 'true' : 'false'}
        )`).join(',');

const generated = `// Generated by scripts/generate-provider-ingestion-catalog.mjs.
// Source of truth: contracts/provider-ingestion-catalog.json. Do not edit manually.

import Foundation
import OpenBurnBarKernel

public enum AgentProviderIngestionCoverage: String, Codable, Sendable {
    case localParser = "local-parser"
    case apiBacked = "api-backed"
    case unavailable
}

public enum AgentProviderIngestionCatalog {
    public struct Entry: Equatable, Sendable {
        public let provider: AgentProvider
        public let agentProviderCase: String
        public let providerID: String
        public let displayLabel: String
        public let aliases: [String]
        public let linuxLogicalPath: String
        public let macOSLogicalPath: String
        public let filePattern: String
        public let ingestion: AgentProviderIngestionCoverage
        public let coverageNote: String
        public let quotaSignal: Bool
    }

    public static let entries: [Entry] = [${entries}
    ]

    private static let entriesByProvider = Dictionary(
        uniqueKeysWithValues: entries.map { ($0.provider, $0) }
    )

    public static func entry(for provider: AgentProvider) -> Entry {
        guard let entry = entriesByProvider[provider] else {
            preconditionFailure("Missing provider ingestion catalog entry for \\(provider.rawValue)")
        }
        return entry
    }

    public static var localParserProviders: Set<AgentProvider> {
        Set(entries.lazy.filter { $0.ingestion == .localParser }.map(\\.provider))
    }

    public static var quotaSignalProviders: Set<AgentProvider> {
        Set(entries.lazy.filter(\\.quotaSignal).map(\\.provider))
    }
}
`;

if (checkOnly) {
  const current = fs.existsSync(swiftPath) ? fs.readFileSync(swiftPath, 'utf8') : '';
  if (current !== generated) {
    console.error(`Generated provider ingestion catalog is stale: ${path.relative(repoRoot, swiftPath)}`);
    process.exit(1);
  }
  console.log('Provider ingestion catalog generation is current.');
} else {
  fs.writeFileSync(swiftPath, generated);
  console.log(`Updated ${path.relative(repoRoot, swiftPath)}`);
}

"""Cross-platform interop tests for ``gateway.crypto.relay_e2ee``.

These mirror the Kotlin suite (``HermesRelayWireVectorTest.kt`` +
``HermesRelayCryptoTest.kt``): Python opens the *same* Swift-generated wire
vector (``tests/gateway/fixtures/HermesRelayWireVector.json``), proving the
Python port is byte-for-byte wire-compatible with the canonical Swift
``HermesRelayCrypto``. The vector itself is generated by
``swift test --package-path OpenBurnBarCore --filter HermesRelayCrossPlatformVectorTests``
and vendored verbatim; its ``revision`` is asserted as the contract key.

``cryptography`` is imported lazily inside the module under test; if it is
unavailable the whole module skips (matching the fork's lazy-import policy).
"""


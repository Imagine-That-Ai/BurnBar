    plaintext = relay_e2ee.open_base64(
        model_switch["payloadCiphertext"], sym, _gw_event_payload_aad(model_switch)
    )
    assert json.loads(plaintext.decode("utf-8")) == {"modelId": "claude-opus-4-8"}



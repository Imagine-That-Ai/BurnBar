package com.openburnbar.data.cloud.signalsession

import com.openburnbar.irohrelay.HermesRealtimeRelayFrame
import com.openburnbar.irohrelay.HermesRealtimeRelayFrameType
import java.util.Base64
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Test
import org.signal.libsignal.protocol.IdentityKeyPair
import org.signal.libsignal.protocol.SessionCipher
import org.signal.libsignal.protocol.SignalProtocolAddress
import org.signal.libsignal.protocol.message.CiphertextMessage
import org.signal.libsignal.protocol.message.PreKeySignalMessage
import org.signal.libsignal.protocol.state.KyberPreKeyRecord
import org.signal.libsignal.protocol.state.PreKeyRecord
import org.signal.libsignal.protocol.state.SignedPreKeyRecord

/**
 * Cross-language interop KAT (the D2 ship-blocker): decrypts a PreKey message produced by
 * the SWIFT `OBBSignalProtocolStore` (Alice) using the Android [AndroidSignalProtocolStore]
 * (Bob), reconstructed from the same key material. Proves the Swift and Android session
 * stores interoperate on the real official-libsignal wire format. The committed fixture is
 * generated by the Swift `OBBSignalInteropFixtureGen` (run on demand) and lives under
 * `src/test/resources/signal-interop/`.
 */
class AndroidSignalInteropKatTest {

    private fun b64(s: String): ByteArray = Base64.getDecoder().decode(s)

    @Test
    fun decryptsSwiftAliceMessage() {
        val raw = javaClass.getResourceAsStream("/signal-interop/swift-alice-to-android-bob.json")
            ?.readBytes()?.toString(Charsets.UTF_8)
            ?: error("interop fixture not found on the test classpath")
        val fx = JSONObject(raw)

        // Reconstruct Bob's store from the Swift-produced key material.
        val bobIdentity = IdentityKeyPair(b64(fx.getString("bobIdentityKeyPairB64")))
        val bob = AndroidSignalProtocolStore.testingTOFU(
            bobIdentity,
            fx.getInt("bobRegistrationId"),
            InMemorySignalRecordVault(),
        )
        bob.storePreKey(fx.getInt("bobPreKeyId"), PreKeyRecord(b64(fx.getString("bobPreKeyRecordB64"))))
        bob.storeSignedPreKey(
            fx.getInt("bobSignedPreKeyId"),
            SignedPreKeyRecord(b64(fx.getString("bobSignedPreKeyRecordB64"))),
        )
        bob.storeKyberPreKey(
            fx.getInt("bobKyberPreKeyId"),
            KyberPreKeyRecord(b64(fx.getString("bobKyberPreKeyRecordB64"))),
        )

        val deviceId = fx.getInt("deviceId")
        val aliceAddress = SignalProtocolAddress(fx.getString("aliceAddressName"), deviceId)
        val bobAddress = SignalProtocolAddress(fx.getString("bobAddressName"), deviceId)

        // Bob (local) decrypts Alice's (remote) PreKey message — SessionCipher(store, LOCAL, REMOTE).
        val cipher = SessionCipher(bob, bobAddress, aliceAddress)
        val plaintext = cipher.decrypt(PreKeySignalMessage(b64(fx.getString("ciphertextB64"))))

        assertEquals(fx.getString("expectedPlaintext"), String(plaintext, Charsets.UTF_8))
    }

    @Test
    fun decryptsSwiftAliceSessionFrame() {
        val raw = javaClass.getResourceAsStream("/signal-interop/swift-alice-to-android-bob.json")
            ?.readBytes()?.toString(Charsets.UTF_8)
            ?: error("interop fixture not found on the test classpath")
        val fx = JSONObject(raw)

        val bobIdentity = IdentityKeyPair(b64(fx.getString("bobIdentityKeyPairB64")))
        val bob = AndroidSignalProtocolStore.testingTOFU(
            bobIdentity,
            fx.getInt("bobRegistrationId"),
            InMemorySignalRecordVault(),
        )
        bob.storePreKey(fx.getInt("bobPreKeyId"), PreKeyRecord(b64(fx.getString("bobPreKeyRecordB64"))))
        bob.storeSignedPreKey(
            fx.getInt("bobSignedPreKeyId"),
            SignedPreKeyRecord(b64(fx.getString("bobSignedPreKeyRecordB64"))),
        )
        bob.storeKyberPreKey(
            fx.getInt("bobKyberPreKeyId"),
            KyberPreKeyRecord(b64(fx.getString("bobKyberPreKeyRecordB64"))),
        )

        val deviceId = fx.getInt("deviceId")
        val aliceAddress = SignalProtocolAddress(fx.getString("aliceAddressName"), deviceId)
        val bobAddress = SignalProtocolAddress(fx.getString("bobAddressName"), deviceId)
        val frame = HermesRealtimeRelayFrame(
            type = HermesRealtimeRelayFrameType.SIGNAL_SESSION_MESSAGE,
            uid = "kat-user",
            connectionId = "swift-frame-kat",
            requestId = "swift-frame-kat-1",
            signalSessionCiphertextB64 = fx.getString("ciphertextB64"),
            signalMessageType = CiphertextMessage.PREKEY_TYPE,
        )

        val received = AndroidSignalSessionManager(bob, bobAddress).decrypt(frame, aliceAddress)

        assertEquals(CiphertextMessage.PREKEY_TYPE, received.messageType)
        assertEquals(fx.getString("expectedPlaintext"), String(received.plaintext, Charsets.UTF_8))
    }
}
